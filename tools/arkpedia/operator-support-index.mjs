import {readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {REGULAR_OPERATORS} from '../../shared/arkpedia/operators.js';
import {renameWithRetry} from './write-json.mjs';
const defaultTarget=new URL('../../shared/arkpedia/operator-support-index.js',import.meta.url);
function plain(value,path) {
  if(value===null||['string','boolean'].includes(typeof value))return;
  if(typeof value==='number'&&Number.isFinite(value))return;
  if(Array.isArray(value)){value.forEach((v,i)=>plain(v,`${path}[${i}]`));return;}
  if(!value||typeof value!=='object'||![Object.prototype,null].includes(Object.getPrototypeOf(value)))
    throw Error(`Non-data operator support: ${path}`);
  for(const[k,v]of Object.entries(value))plain(v,`${path}.${k}`);
}
export function buildOperatorSupportIndex(registry=REGULAR_OPERATORS) {
  plain(registry,'operators');
  for(const[id,entry]of Object.entries(registry))
    if(!/^char_\w+$/.test(id)||!entry||!Array.isArray(entry.talentKeys)||entry.talentKeys.some(k=>typeof k!=='string')
      ||entry.mechanic!==undefined&&(typeof entry.mechanic!=='string'||!entry.mechanic))
      throw Error(`Invalid operator support: ${id}`);
  return '// SPDX-License-Identifier: GPL-3.0-or-later\n'
    +'// Generated by tools/arkpedia/operator-support-index.mjs from source registrations. Do not edit.\n'
    +'export const REGULAR_OPERATORS=Object.freeze('+JSON.stringify(registry)+');\n';
}
export async function checkOperatorSupportIndex(target=defaultTarget) {
  if(await readFile(target,'utf8')!==buildOperatorSupportIndex())throw Error('Operator support index is stale');
}
export async function publishOperatorSupportIndex(target=defaultTarget) {
  const temporary=new URL(`.operator-support-index.${randomUUID()}.tmp`,target);
  await mkdir(new URL('.',target),{recursive:true});
  try{await writeFile(temporary,buildOperatorSupportIndex(),{flag:'wx'});await renameWithRetry(temporary,target);}
  finally{await rm(temporary,{force:true});}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  if(process.argv.includes('--check'))await checkOperatorSupportIndex();else await publishOperatorSupportIndex();
  console.log(JSON.stringify({operators:Object.keys(REGULAR_OPERATORS).length,bytes:Buffer.byteLength(buildOperatorSupportIndex())}));
}
